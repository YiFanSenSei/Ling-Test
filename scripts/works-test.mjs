import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { mkdtempSync, rmSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createApp } from '../server/app.mjs';
import { openTestBrowser } from './lib/browser-test.mjs';

const root = resolve(import.meta.dirname, '..'), directory = mkdtempSync(join(tmpdir(), 'jz-works-browser-'));
const password = randomBytes(24).toString('hex');
const server = createApp({ dataDir: directory, distDir: join(root, 'dist'), adminPassword: password });
await new Promise(ready => server.listen(0, '127.0.0.1', ready));
const base = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser = await openTestBrowser();
  const { evaluate: run, wait, send, click } = browser;
  await browser.go(base + '/#/simulator?tool=embroidery', "document.getElementById('canvas-embroidery')");
  await click('[data-template="free"]');
  await run("document.getElementById('canvas-embroidery').scrollIntoView({block:'center',behavior:'instant'})");
  const point = await run(`(() => {const r=document.getElementById('canvas-embroidery').getBoundingClientRect();return {x:r.x+r.width*.3,y:r.y+r.height*.5};})()`);
  await send('Input.dispatchMouseEvent', { type: 'mousePressed', ...point, button: 'left', buttons: 1, clickCount: 1 });
  await send('Input.dispatchMouseEvent', { type: 'mouseMoved', x: point.x + 120, y: point.y + 30, buttons: 1 });
  await send('Input.dispatchMouseEvent', { type: 'mouseReleased', x: point.x + 120, y: point.y + 30, button: 'left', buttons: 0, clickCount: 1 });
  await wait("!document.getElementById('craft-result-embroidery').hidden");
  await click('[data-submit-work="embroidery"]'); await wait("document.getElementById('work-dialog').open");
  const originalPreview = await run("document.getElementById('work-preview').src");
  await run("document.getElementById('work-title').value='   '"); await click('#work-submit-button');
  assert.equal(await run("document.getElementById('work-title').validity.customError"),true);
  assert.equal(await run("document.getElementById('work-submit-button').disabled"),false);
  await run("document.getElementById('work-title').value='浏览器验证作品'");
  await run("document.getElementById('work-title').dispatchEvent(new Event('input'))");
  assert.notEqual(await run("document.getElementById('work-preview').src"),originalPreview);
  await run("document.getElementById('work-nickname').value='访客甲';document.getElementById('work-nickname').dispatchEvent(new Event('input'))");
  const editedPreview = await run("document.getElementById('work-preview').src");
  await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 });
  await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 });
  await wait("!document.getElementById('work-dialog').open && !document.body.classList.contains('work-submit-open')");
  assert.equal(await run('document.activeElement.dataset.submitWork'), 'embroidery');
  await click('[data-submit-work="embroidery"]');
  assert.equal(await run("document.getElementById('work-title').value"), '浏览器验证作品');
  assert.equal(await run("document.getElementById('work-nickname').value"), '访客甲');
  assert.equal(await run("document.getElementById('work-preview').src"), editedPreview);
  assert(await run("document.body.classList.contains('work-submit-open')"));
  await run(`window.__submitBodies=[];const originalFetch=window.fetch;window.fetch=async function(url,options){
    if(url==='/api/works' && options?.method==='POST'){
      window.__submitBodies.push(options.body);const response=await originalFetch.call(this,url,options);
      if(window.__submitBodies.length===1)throw new TypeError('模拟响应丢失');
      if(window.__submitBodies.length===2)return new Response('{}',{status:200,headers:{'Content-Type':'application/json'}});
      await new Promise(resolve=>window.__finishSubmit=resolve);return response;
    }return originalFetch.call(this,url,options);
  }`);
  await click('#work-submit-button'); await wait("document.getElementById('work-submit-status').textContent.includes('本地作品仍保留')");
  await click('#work-dialog-close'); await wait("!document.body.classList.contains('work-submit-open')");
  await click('[data-submit-work="embroidery"]');
  await click('#work-submit-button'); await wait("document.getElementById('work-submit-status').textContent.includes('有效的保存回执')");
  assert.equal(await run("document.getElementById('work-submit-button').hidden"), false);
  await click('#work-submit-button'); await wait('window.__finishSubmit');
  await click('#work-dialog-close'); await wait("!document.body.classList.contains('work-submit-open')");
  await click('[data-submit-work="embroidery"]');
  assert(await run("document.getElementById('work-submit-button').disabled && document.getElementById('work-refresh-preview').disabled"));
  await click('#work-dialog-close'); await wait("!document.body.classList.contains('work-submit-open')");
  await click('#tab-mortise');
  for (let i = 0; i < 10; i++) await click('#advance-mortise');
  await wait("!document.getElementById('craft-result-mortise').hidden");
  await click('[data-submit-work="mortise"]');
  const mortiseTitle = await run("document.getElementById('work-title').value");
  assert.notEqual(mortiseTitle, '浏览器验证作品');
  await run('window.__finishSubmit()');
  // 给旧请求一个事件循环收尾：不能把榫卯表单改成苏绣的提交成功状态。
  await run('new Promise(resolve=>setTimeout(resolve,50))');
  assert.equal(await run("document.getElementById('work-submit-button').hidden"), false);
  assert.equal(await run("document.getElementById('work-submit-status').textContent"), '');
  await click('#work-dialog-close'); await wait("!document.body.classList.contains('work-submit-open')");
  await click('#tab-embroidery');
  await click('[data-submit-work="embroidery"]');
  await wait("document.getElementById('work-submit-status').textContent.includes('编号')");
  assert(await run("window.__submitBodies.length===3 && window.__submitBodies.every(body=>body===window.__submitBodies[0])"));
  await run("document.getElementById('work-submit-form').dispatchEvent(new Event('submit',{cancelable:true}))");
  assert.equal(await run("window.__submitBodies.length"),3);
  const submittedPreview = await run("document.getElementById('work-preview').src");
  await click('#work-dialog-close'); await wait("!document.body.classList.contains('work-submit-open')");
  await run("document.getElementById('canvas-embroidery').scrollIntoView({block:'center',behavior:'instant'})");
  await run('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
  const beforeMoreStitches = await run("Number(document.getElementById('stitch-count').textContent)");
  const nextPoint = await run("(()=>{const r=document.getElementById('canvas-embroidery').getBoundingClientRect();return {x:r.x+r.width*.4,y:r.y+r.height*.7}})()");
  await send('Input.dispatchMouseEvent', { type: 'mousePressed', ...nextPoint, button: 'left', buttons: 1, clickCount: 1 });
  await send('Input.dispatchMouseEvent', { type: 'mouseMoved', x: nextPoint.x + 160, y: nextPoint.y, buttons: 1 });
  await send('Input.dispatchMouseEvent', { type: 'mouseReleased', x: nextPoint.x + 160, y: nextPoint.y, button: 'left', buttons: 0, clickCount: 1 });
  assert(await run(`Number(document.getElementById('stitch-count').textContent)>${beforeMoreStitches}`), '继续创作应增加针脚');
  // 画布已经改变；打开时仍保留已提交预览，只有主动更新才换成新图。
  await click('[data-submit-work="embroidery"]');
  assert.equal(await run("document.getElementById('work-preview').src"), submittedPreview);
  await click('#work-refresh-preview');
  assert((await run("document.getElementById('work-preview').src")) !== submittedPreview, '使用最新画布应更新预览图');
  assert(await run("!document.getElementById('work-submit-button').hidden && !document.getElementById('work-title').disabled"));
  assert.equal(await run("document.getElementById('work-title').value"), '浏览器验证作品');
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  assert(await run('document.documentElement.scrollWidth <= innerWidth'));
  await run('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
  mkdirSync(join(root, '_shots'), { recursive: true });
  const dialogShot = await send('Page.captureScreenshot', { format: 'png' });
  writeFileSync(join(root, '_shots/submission-mobile.png'), Buffer.from(dialogShot.data, 'base64'));
  await run("location.hash='#/works'"); await wait("document.getElementById('works-content')");
  assert.equal(await run("document.body.classList.contains('work-submit-open')"), false);
  console.log('✓ 真实画布作品可预览并投稿，得到服务端保存编号');
  console.log('✓ 关闭保留标题/昵称/预览；丢失与畸形回执重试复用同一请求；提交中关闭后仍保留回执，成功后阻止重复提交');
  console.log('✓ 更新画布可开始新投稿，390px 弹窗无横向溢出，切页释放滚动锁');
  await browser.go(base + '/#/works', "document.querySelector('.works-message')");
  assert.equal(await run("document.querySelectorAll('.visitor-work').length"), 0);
  await browser.go(base + '/admin', "document.getElementById('password')");
  await run(`document.getElementById('password').value=${JSON.stringify(password)}`);
  await click('#login button'); await wait("document.querySelector('.work button')");
  assert.equal(await run("document.querySelectorAll('.work').length"),1);
  assert.equal(await run("document.querySelector('.work h2').textContent"), '浏览器验证作品');
  await click('.work button'); await wait("document.getElementById('notice').textContent.includes('审核已保存')");
  console.log('✓ 审核前作品不公开，管理员可在网页中审核通过');
  await browser.go(base + '/#/works', "document.querySelector('.visitor-work')");
  assert.equal(await run("document.querySelector('.visitor-work h2').textContent"), '浏览器验证作品');
  await wait("document.querySelector('.visitor-work img').naturalWidth > 0");
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  assert(await run('document.documentElement.scrollWidth <= innerWidth'));
  mkdirSync(join(root, '_shots'), { recursive: true });
  const shot = await send('Page.captureScreenshot', { format: 'png' });
  writeFileSync(join(root, '_shots/works-mobile.png'), Buffer.from(shot.data, 'base64'));
  console.log('✓ 审核后作品和图片出现在作品墙，手机无横向溢出');
  await browser.go(pathToFileURL(join(root, 'dist/index.html')).href + '#/works', "document.querySelector('.works-message')");
  assert((await run("document.querySelector('.works-message').textContent")).includes('离线'));
  assert.equal(browser.errors.length, 0, browser.errors.join('\n'));
  console.log('✓ 离线版本明确说明在线功能，不产生无效投稿请求');
} finally {
  browser?.close(); await new Promise(ready => server.close(ready));
  if (resolve(directory).startsWith(resolve(tmpdir()) + sep)) rmSync(directory, { recursive: true, force: true });
}
